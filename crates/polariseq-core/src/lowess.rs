    fn close(fit: &[f64], expected: &[f64]) {
        for (k, (a, b)) in fit.iter().zip(expected).enumerate() {
            assert!(
                (a - b).abs() < 1e-8 * (1.0 + b.abs()),
                "point {k}: {a} vs statsmodels {b}"
            );
        }
    }

