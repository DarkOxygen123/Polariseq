//! LOWESS (locally weighted scatterplot smoothing; Cleveland 1979), as
//! `statsmodels.nonparametric.smoothers_lowess.lowess` computes it with
//! `delta = 0`: for each point a weighted straight-line fit over its `k`
//! nearest neighbours in `x` (tricube weights scaled to the farthest of
//! them), followed by `it` robustifying passes that down-weight points with
//! large residuals (bisquare weights of the residual over six times the
//! median absolute residual).
//!
//! Used by [`crate::preprocess::hvg_scarf`] on a few hundred points (one per
//! mean-expression bin), so it is written for clarity, not for scale.

#![allow(clippy::cast_precision_loss, clippy::many_single_char_names)]

/// Fitted values at each input point, in the input order
/// (`return_sorted=False`). `frac` is the share of points in each local fit,
/// `it` the number of robustifying passes.
///
/// # Panics
/// Panics if `x` and `y` differ in length.
#[must_use]
pub fn lowess(x: &[f64], y: &[f64], frac: f64, it: usize) -> Vec<f64> {
    assert_eq!(x.len(), y.len(), "x and y must have the same length");
    let n = x.len();
    if n == 0 {
        return Vec::new();
    }
    if n == 1 {
        return vec![y[0]];
    }
    // Work on the points sorted by x (stable, so ties keep their order).
    let mut order: Vec<usize> = (0..n).collect();
    order.sort_by(|&a, &b| x[a].partial_cmp(&x[b]).unwrap_or(std::cmp::Ordering::Equal));
    let xs: Vec<f64> = order.iter().map(|&i| x[i]).collect();
    let ys: Vec<f64> = order.iter().map(|&i| y[i]).collect();

    // statsmodels: k = int(frac * n + 1e-10), held within [2, n].
    let k = ((frac * n as f64 + 1e-10) as usize).clamp(2, n);
    let mut robust = vec![1.0_f64; n];
    let mut fitted = vec![0.0_f64; n];
    for pass in 0..=it {
        fit_pass(&xs, &ys, &robust, k, &mut fitted);
        if pass == it {
            break;
        }
        // Robustness weights from this pass's residuals.
        let resid: Vec<f64> = ys.iter().zip(&fitted).map(|(a, b)| (a - b).abs()).collect();
        let mut sorted = resid.clone();
        sorted.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
        let median = if n % 2 == 1 {
            sorted[n / 2]
        } else {
            0.5 * (sorted[n / 2 - 1] + sorted[n / 2])
        };
        if median <= 0.0 {
            break; // a perfect fit: nothing to robustify
        }
        let scale = 6.0 * median;
        for (w, r) in robust.iter_mut().zip(&resid) {
            let u = r / scale;
            *w = if u >= 1.0 { 0.0 } else { (1.0 - u * u).powi(2) };
        }
    }
    let mut out = vec![0.0_f64; n];
    for (pos, &i) in order.iter().enumerate() {
        out[i] = fitted[pos];
    }
    out
}

/// One pass of local linear fits over sorted `xs`, with robustness weights.
fn fit_pass(xs: &[f64], ys: &[f64], robust: &[f64], k: usize, fitted: &mut [f64]) {
    let n = xs.len();
    let mut left = 0_usize; // the window [left, left + k) of the k nearest points
    for i in 0..n {
        // Slide the window right while the point leaving on the left is
        // farther from x_i than the one that would enter on the right.
        while left + k < n && xs[i] - xs[left] > xs[left + k] - xs[i] {
            left += 1;
        }
        let right = left + k; // exclusive
        let radius = (xs[i] - xs[left]).max(xs[right - 1] - xs[i]);
        let mut w = vec![0.0_f64; k];
        let mut total = 0.0;
        for (j, wj) in (left..right).zip(w.iter_mut()) {
            let tri = if radius > 0.0 {
                let d = (xs[j] - xs[i]).abs() / radius;
                if d >= 1.0 {
                    0.0
                } else {
                    (1.0 - d * d * d).powi(3)
                }
            } else {
                1.0 // all neighbours at the same x
            };
            *wj = tri * robust[j];
            total += *wj;
        }
        if total <= 0.0 {
            fitted[i] = ys[i];
            continue;
        }
        for wj in &mut w {
            *wj /= total;
        }
        let mean_x: f64 = (left..right).zip(&w).map(|(j, wj)| wj * xs[j]).sum();
        let var_x: f64 = (left..right)
            .zip(&w)
            .map(|(j, wj)| wj * (xs[j] - mean_x).powi(2))
            .sum();
        let mut fit = 0.0;
        for (j, wj) in (left..right).zip(&w) {
            let lever = if var_x > 1e-12 {
                1.0 + (xs[i] - mean_x) * (xs[j] - mean_x) / var_x
            } else {
                1.0
            };
            fit += wj * lever * ys[j];
        }
        fitted[i] = fit;
    }
}

